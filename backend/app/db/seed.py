"""Idempotent seed: `python -m app.db.seed [--skip-embeddings | --embeddings-only] [--data PATH]`.

Imports the supplied BookLeaf JSON without modifying it, creates demo login accounts (passwords are
generated by this application, not part of the dataset), and loads the knowledge base.
"""
import argparse
import asyncio
import json
import logging
from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from pathlib import Path
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.ai.errors import AIError
from app.ai.knowledge_base import embed_missing_chunks, sync_knowledge_sections
from app.ai.providers.gemini import GeminiProvider
from app.core.config import get_settings
from app.core.logging import configure_logging
from app.core.security import hash_password
from app.db.session import build_engine, build_session_factory
from app.models import Author, Book, BookAvailability, User
from app.models.enums import Role

logger = logging.getLogger("seed")

DEFAULT_DATA = Path(__file__).resolve().parents[2] / "data" / "bookleaf_sample_data.json"
AUTHOR_DEMO_PASSWORD = "Author@123"
ADMIN_EMAIL = "admin@bookleaf.com"
ADMIN_DEMO_PASSWORD = "Admin@123"


@dataclass
class SeedReport:
    authors: int = 0
    books: int = 0
    users_created: int = 0


def _date(value: Any) -> date | None:
    return date.fromisoformat(value) if value else None


def _money(value: Any, default: Decimal | None = None) -> Decimal | None:
    return Decimal(str(value)) if value is not None else default


def normalise_dataset(raw: dict) -> list[tuple[dict, list[dict]]]:
    """Accept nested (authors[].books[]) or flat (authors[] + books[] with author_id) layouts."""
    authors = raw["authors"]
    flat_books = raw.get("books", [])
    result = []
    for author in authors:
        books = list(author.get("books", []))
        books += [b for b in flat_books if b.get("author_id") == author["author_id"]]
        result.append((author, books))
    return result


async def _upsert_user(session: AsyncSession, email: str, role: Role, password: str) -> tuple[User, bool]:
    email = email.lower()
    user = (await session.execute(select(User).where(User.email == email))).scalar_one_or_none()
    if user:
        return user, False
    user = User(email=email, role=role, password_hash=hash_password(password), is_active=True)
    session.add(user)
    await session.flush()
    return user, True


async def seed_operational_data(session: AsyncSession, data_path: Path = DEFAULT_DATA) -> SeedReport:
    report = SeedReport()
    raw = json.loads(data_path.read_text(encoding="utf-8"))

    _, created = await _upsert_user(session, ADMIN_EMAIL, Role.ADMIN, ADMIN_DEMO_PASSWORD)
    report.users_created += created

    for author_json, books_json in normalise_dataset(raw):
        user, created = await _upsert_user(session, author_json["email"], Role.AUTHOR, AUTHOR_DEMO_PASSWORD)
        report.users_created += created

        author = (await session.execute(
            select(Author).where(Author.external_author_id == author_json["author_id"])
        )).scalar_one_or_none() or Author(external_author_id=author_json["author_id"])
        author.user_id = user.id
        author.name = author_json["name"]
        author.email = author_json["email"]
        author.phone = author_json.get("phone")
        author.city = author_json.get("city")
        author.joined_date = _date(author_json.get("joined_date"))
        session.add(author)
        await session.flush()
        report.authors += 1

        for b in books_json:
            book = (await session.execute(
                select(Book).where(Book.external_book_id == b["book_id"])
            )).scalar_one_or_none() or Book(external_book_id=b["book_id"])
            book.author_id = author.id
            book.title = b["title"]
            book.isbn = b.get("isbn")
            book.genre = b.get("genre")
            book.publication_date = _date(b.get("publication_date"))
            book.status = b.get("status") or "Unknown"
            book.mrp = _money(b.get("mrp"))
            book.author_royalty_per_copy = _money(b.get("author_royalty_per_copy"))
            book.total_copies_sold = int(b.get("total_copies_sold") or 0)
            book.total_royalty_earned = _money(b.get("total_royalty_earned"), Decimal(0))
            book.royalty_paid = _money(b.get("royalty_paid"), Decimal(0))
            book.royalty_pending = _money(b.get("royalty_pending"), Decimal(0))
            book.last_royalty_payout_date = _date(b.get("last_royalty_payout_date"))
            book.print_partner = b.get("print_partner")
            session.add(book)
            await session.flush()

            # Source order of `available_on` is preserved (rows are read back by insertion id).
            wanted = list(dict.fromkeys(b.get("available_on") or []))
            existing = list((await session.execute(
                select(BookAvailability).where(BookAvailability.book_id == book.id).order_by(BookAvailability.id)
            )).scalars())
            if [row.platform for row in existing] != wanted:
                for row in existing:
                    await session.delete(row)
                await session.flush()
                session.add_all(BookAvailability(book_id=book.id, platform=p) for p in wanted)
            report.books += 1
    return report


async def seed_knowledge_base(session: AsyncSession, *, embed: bool) -> str:
    count = await sync_knowledge_sections(session)
    if not embed:
        return f"{count} KB sections synced (embeddings skipped)."
    settings = get_settings()
    if not settings.ai_configured:
        return f"{count} KB sections synced. GEMINI_API_KEY not set: embeddings skipped (run `python -m app.db.seed --embeddings-only` later)."
    try:
        embedded = await embed_missing_chunks(session, GeminiProvider(settings))
    except AIError as exc:
        return f"{count} KB sections synced. Embedding failed ({exc.message}); retry with `--embeddings-only`."
    return f"{count} KB sections synced, {embedded} newly embedded."


async def run(args: argparse.Namespace) -> None:
    settings = get_settings()
    engine = build_engine(settings)
    factory = build_session_factory(engine)
    try:
        async with factory() as session:
            if not args.embeddings_only:
                report = await seed_operational_data(session, Path(args.data))
                await session.commit()
                logger.info("Seeded %d authors, %d books (%d new user accounts).", report.authors, report.books, report.users_created)
            logger.info(await seed_knowledge_base(session, embed=not args.skip_embeddings))
            await session.commit()
    finally:
        await engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed the BookLeaf support database (idempotent).")
    parser.add_argument("--data", default=str(DEFAULT_DATA), help="Path to the BookLeaf JSON dataset")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--skip-embeddings", action="store_true", help="Seed data but do not call Gemini")
    group.add_argument("--embeddings-only", action="store_true", help="Only (re)generate missing KB embeddings")
    configure_logging()
    asyncio.run(run(parser.parse_args()))


if __name__ == "__main__":
    main()
